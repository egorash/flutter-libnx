// Время по счётчику AArch64.
//
// Единственное место в порту, где считают время. Существует по конкретной
// причине: armGetSystemTick() возвращает СЫРЫЕ ТИКИ cntpct_el0, а не
// наносекунды. Частота на Horizon - 19,2 МГц, то есть один тик равен
// 52,08 нс.
//
// На этом уже ошибались дважды, и обе ошибки выглядели безобидно:
//
//   * геймпад опрашивался не 60 раз в секунду, а 1,15 - потому что период
//     «1000000000 / 60» сравнивался с тиками. Кнопка, нажатая короче
//     окна опроса (868 мс), просто терялась. В протоколе при этом стояло
//     «Abfrage laeuft, 60 Hz» - цифра из константы, а не из измерения;
//   * в протокол писалось время, заниженное в 52 раза, из-за чего одни
//     и те же числа читались то как полсекунды, то как сорок секунд.
//
// Отсюда правило: внутри кода - только тики через эти функции. Наносекунды
// нужны исключительно там, где их ждёт ядро (таймауты svcWaitSynchronization
// и waitSingleHandle) - там стоит armTicksToNs().

#pragma once

#include <switch.h>

namespace flutter_libnx {

/// Текущее значение счётчика в тиках.
inline u64 TickNow() {
  return armGetSystemTick();
}

/// Тики -> миллисекунды.
inline u64 TickToMs(u64 ticks) {
  return ticks * 1000 / armGetSystemTickFreq();
}

/// Микросекунды -> тики.
inline u64 UsToTick(u64 micros) {
  return micros * armGetSystemTickFreq() / 1000000;
}

/// Наносекунды -> тики. Нужна редко: почти всё внутри кода живёт в тиках.
inline u64 NsToTick(u64 nanos) {
  return nanos * armGetSystemTickFreq() / 1000000000ULL;
}

/// Тики -> наносекунды. Единственное, ради чего в этом файле есть
/// обращение к armTicksToNs: таймауты ожидания ждёт ядро, и там единица
/// измерения - именно наносекунды.
inline u64 TickToNs(u64 ticks) {
  return armTicksToNs(ticks);
}

/// Разность тиков в миллисекундах. Порядок аргументов тот же, что у
/// счётчика: TickMsSince(start).
inline u64 TickMsSince(u64 start) {
  return TickToMs(TickNow() - start);
}

}  // namespace flutter_libnx